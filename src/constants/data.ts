function makeStudentBreakdown(
  students: typeof STUDENTS,
  avgFee: number,
  debtCount: number,
  months: string[],
): StudentBreakdown[] {
  return students.map((s, i) => {
    const inDebt = i < debtCount;
    const paidMonths = inDebt ? months.slice(0, -1) : months;
    const pendingMonths = inDebt ? months.slice(-1) : [];

    const totalPaid = paidMonths.length * avgFee;
    const totalPending = pendingMonths.length * avgFee;
    const totalLateFee = inDebt ? Math.round(avgFee * 0.1) : 0;

    return {
      student: s,
      totalPaid,
      totalPending,
      totalLateFee,
      monthlyPayments: [
        ...paidMonths.map((m) => ({
          monthName: m,
          amount: avgFee,
          lateFee: 0,
          status: 'PAID' as TPaymentStatus,
        })),
        ...pendingMonths.map((m) => ({
          monthName: m,
          amount: avgFee,
          lateFee: Math.round(avgFee * 0.1),
          status: 'PENDING' as TPaymentStatus,
        })),
      ],
    };
  });
}
