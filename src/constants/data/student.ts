const acAvg = (ac: number[]) =>
  Math.round((ac.reduce((a, b) => a + b, 0) / ac.length) * 100) / 100;

// examAverage = (acAverage * 0.4) + (exam * 0.6)
const calcExamAvg = (acAverage: number, exam: number) =>
  Math.round((acAverage * 0.4 + exam * 0.6) * 100) / 100;

// retakeAverage = (acAverage * 0.4) + (retake * 0.6)
const calcRetakeAvg = (acAverage: number, retake: number) =>
  Math.round((acAverage * 0.4 + retake * 0.6) * 100) / 100;
